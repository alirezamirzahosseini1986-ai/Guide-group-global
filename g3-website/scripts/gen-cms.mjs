// Regenerates .pages.yml (Pages CMS panel config) from the content files.
// Run after changing the structure of any content JSON:  npm run cms
import fs from "node:fs";
import { pagesCmsConfig } from "../src/lib/cms.js";

const toYaml = (v, ind = "") => {
  if (Array.isArray(v)) return v.map((x) => `\n${ind}- ${toYaml(x, ind + "  ").replace(/^\n\s*/, "")}`).join("");
  if (v && typeof v === "object")
    return Object.entries(v)
      .filter(([, x]) => x !== undefined)
      .map(([k, x]) => (typeof x === "object" ? `\n${ind}${k}:${toYaml(x, ind + "  ")}` : `\n${ind}${k}: ${JSON.stringify(x)}`))
      .join("");
  return JSON.stringify(v);
};
fs.writeFileSync(".pages.yml", "# Generated by scripts/gen-cms.mjs — panel: https://app.pagescms.org" + toYaml(pagesCmsConfig()) + "\n");
console.log("wrote .pages.yml");
