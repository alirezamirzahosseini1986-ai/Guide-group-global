// Generates src/js/globe-data.js: points on land (Fibonacci sphere) for the 3D globe.
import fs from "node:fs";
import { feature } from "topojson-client";
import { geoContains } from "d3-geo";
const topo = JSON.parse(fs.readFileSync("node_modules/world-atlas/land-110m.json"));
const land = feature(topo, topo.objects.land);
const N = 22000, out = [];
const golden = Math.PI * (3 - Math.sqrt(5));
for (let i = 0; i < N; i++) {
  const y = 1 - (i / (N - 1)) * 2, r = Math.sqrt(1 - y * y), t = golden * i;
  const lat = Math.asin(y) * 180 / Math.PI;
  const lon = ((Math.atan2(Math.sin(t) * r, Math.cos(t) * r) * 180 / Math.PI) + 540) % 360 - 180;
  if (lat < -60) continue;
  if (geoContains(land, [lon, lat])) out.push(+lat.toFixed(2), +lon.toFixed(2));
}
fs.writeFileSync("src/js/globe-data.js", `// Generated by scripts/build-globe.mjs — land points [lat, lon, …]\nexport const DOTS = new Float32Array([${out.join(",")}]);\n`);
console.log("land dots:", out.length / 2, "bytes:", fs.statSync("src/js/globe-data.js").size);
